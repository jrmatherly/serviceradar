#!/bin/sh
# Entrypoint for the fork-local disposable CNPG used by the DB-backed
# elixir/serviceradar_core tests (make test-db-up). The serviceradar-cnpg image
# ships no docker-entrypoint, so this runs initdb itself.
#
# State lives in the named volume at /var/lib/postgresql. /out is the repo's
# tmp/test-db bind mount and only receives what the host needs on every start:
# ca.pem and .env. The CA key is deleted once the server cert is signed.
#
# The test database guard (config/test_database_guard.exs) accepts an IP host
# only with the srql-fixtures TLS name and sslmode=verify-full, so the server
# cert carries that name plus IP:127.0.0.1.
set -eu

ROOT=/var/lib/postgresql
PGDATA="$ROOT/data"
STATE="$ROOT/test-db"
TLS="$STATE/tls"
OUT=/out
FIXTURE_NAME=srql-fixture-rw.srql-fixtures.svc.cluster.local
HOST_PORT="${TEST_DB_PORT:-55432}"
export PGDATA

make_tls() {
  mkdir -p "$TLS"
  openssl req -x509 -newkey rsa:2048 -nodes -days 3650 \
    -subj "/CN=ServiceRadar local test-db CA" \
    -addext "basicConstraints=critical,CA:TRUE" \
    -addext "keyUsage=critical,keyCertSign,cRLSign" \
    -keyout "$TLS/ca-key.pem" -out "$TLS/ca.pem" 2>/dev/null
  printf 'subjectAltName=DNS:%s,IP:127.0.0.1\nextendedKeyUsage=serverAuth\nkeyUsage=critical,digitalSignature,keyEncipherment\n' \
    "$FIXTURE_NAME" >"$TLS/server.ext"
  openssl req -new -newkey rsa:2048 -nodes -subj "/CN=$FIXTURE_NAME" \
    -keyout "$TLS/server-key.pem" -out "$TLS/server.csr" 2>/dev/null
  openssl x509 -req -in "$TLS/server.csr" -CA "$TLS/ca.pem" -CAkey "$TLS/ca-key.pem" \
    -CAcreateserial -days 825 -extfile "$TLS/server.ext" -out "$TLS/server.pem" 2>/dev/null
  rm -f "$TLS/ca-key.pem" "$TLS/server.csr" "$TLS/ca.srl" "$TLS/server.ext"
}

# A start that died part-way leaves no marker, so it is redone from scratch.
initialize() {
  rm -rf "$PGDATA" "$STATE"
  mkdir -p "$STATE"
  openssl rand -hex 24 >"$STATE/srql-password"
  make_tls

  initdb -D "$PGDATA" --username=postgres --auth-local=trust \
    --auth-host=scram-sha-256 --encoding=UTF8 --locale=C >/dev/null
  # Docker's NAT presents host clients from a non-loopback address.
  echo "hostssl all all all scram-sha-256" >>"$PGDATA/pg_hba.conf"

  pg_ctl -D "$PGDATA" -w -l "$STATE/init.log" \
    -o "-c listen_addresses='' -c unix_socket_directories=/tmp -c shared_preload_libraries=timescaledb,age" \
    start
  psql -X -q -v ON_ERROR_STOP=1 -h /tmp -U postgres -d postgres \
    -v owner_password="$(cat "$STATE/srql-password")" -f /test-db/init.sql
  pg_ctl -D "$PGDATA" -m fast -w stop

  touch "$STATE/initialized"
}

publish_connection() {
  cp "$TLS/ca.pem" "$OUT/ca.pem"
  cat >"$OUT/.env.tmp" <<EOF
# Generated by docker/compose/test-db/entrypoint.sh on every start. Do not commit.
# The CA is ca.pem beside this file; set SERVICERADAR_TEST_DATABASE_CA_CERT_FILE to its absolute path.
SERVICERADAR_TEST_DATABASE_URL='postgres://srql:$(cat "$STATE/srql-password")@127.0.0.1:${HOST_PORT}/sr_core_test_local?sslmode=verify-full'
SERVICERADAR_TEST_DATABASE_SERVER_NAME=$FIXTURE_NAME
EOF
  chmod 600 "$OUT/.env.tmp"
  mv "$OUT/.env.tmp" "$OUT/.env"
}

umask 077
[ -f "$STATE/initialized" ] || initialize
publish_connection

exec postgres -D "$PGDATA" \
  -c listen_addresses='*' \
  -c shared_preload_libraries=timescaledb,age \
  -c ssl=on \
  -c ssl_cert_file="$TLS/server.pem" \
  -c ssl_key_file="$TLS/server-key.pem" \
  -c max_connections=200 \
  -c fsync=off
